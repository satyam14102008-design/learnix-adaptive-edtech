def find_misconception_by_id(misc_id: str) -> Dict[str, Any] | None:
    for m in PHYSICS_MISCONCEPTIONS:
        if m["id"] == misc_id:
            return m
    return None

def detect_misconception_in_text(reasoning_text: str, concept_id: str = "") -> Dict[str, Any] | None:
    """Analyzes reasoning text against known misconception signatures."""
    if not reasoning_text or len(reasoning_text.strip()) < 5:
        return None
        
    lower_text = reasoning_text.lower()
    
    # Check concept-specific misconceptions first
    for misc in PHYSICS_MISCONCEPTIONS:
        if concept_id and misc["concept_id"] != concept_id and misc["chapter_id"] != concept_id:
            continue
        for kw in misc["keywords"]:
            if kw in lower_text:
                return misc
                
    # Check all misconceptions if not found
    for misc in PHYSICS_MISCONCEPTIONS:
        for kw in misc["keywords"]:
            if kw in lower_text:
                return misc
                
    return None
